var COLORS = {
  red:    { main: "#e2473a", accent: "#ffb84d" },
  blue:   { main: "#3f7fd9", accent: "#9be7ff" },
  green:  { main: "#4caf50", accent: "#e6ee5a" },
  gold:   { main: "#e0b030", accent: "#ff7043" },
  purple: { main: "#8e5bd6", accent: "#ff8ad8" },
  silver: { main: "#b8c0cc", accent: "#6ec6ff" },
  black:  { main: "#4a4a60", accent: "#ff4d4d" },
}
var COLOR_NAMES = ["red", "blue", "green", "gold", "purple", "silver", "black"]

function _mix(hex, target, t) {
  var r = parseInt(hex.substr(1, 2), 16), g = parseInt(hex.substr(3, 2), 16), b = parseInt(hex.substr(5, 2), 16)
  var tr = (target >> 16) & 255, tg = (target >> 8) & 255, tb = target & 255
  function c(v, tv) { return Math.round(v + (tv - v) * t) }
  return "rgb(" + c(r, tr) + "," + c(g, tg) + "," + c(b, tb) + ")"
}

var _palettes = {}

function _rgb(c) {
  if (c.charAt(0) === "#") return [parseInt(c.substr(1, 2), 16), parseInt(c.substr(3, 2), 16), parseInt(c.substr(5, 2), 16)]
  var m = /(\d+)\D+(\d+)\D+(\d+)/.exec(c)
  return [Number(m[1]), Number(m[2]), Number(m[3])]
}
// A sulking dragon loses most of its colour and a little brightness.
function _dull(c) {
  var v = _rgb(c), l = 0.3 * v[0] + 0.59 * v[1] + 0.11 * v[2]
  function f(x) { return Math.round((x + (l - x) * 0.66) * 0.9) }
  return "rgb(" + f(v[0]) + "," + f(v[1]) + "," + f(v[2]) + ")"
}

// char -> fill style (cached per colour and mood).
function palette(colorName, dull) {
  var key = colorName + (dull ? "|dull" : "")
  if (_palettes[key]) return _palettes[key]
  var c = COLORS[colorName] || COLORS.red
  var pal = {
    o: _mix(c.main, 0x0b0b12, 0.75),
    m: c.main,
    d: _mix(c.main, 0x0b0b12, 0.38),
    h: _mix(c.main, 0xffffff, 0.35),
    l: _mix(c.main, 0xffffff, 0.62),
    b: _mix(c.accent, 0xffffff, 0.3),
    a: c.accent,
    w: _mix(c.main, 0x0b0b12, 0.15),
    t: "#f6f1e4",
    e: "#ffffff",
    k: "#12121a",
    f: "#ff8a24",
    y: "#ffe27a",
  }
  if (dull) {
    var chars = ["o", "m", "d", "h", "l", "b", "a", "w"]
    for (var i = 0; i < chars.length; i++) pal[chars[i]] = _dull(pal[chars[i]])
  }
  _palettes[key] = pal
  return pal
}

